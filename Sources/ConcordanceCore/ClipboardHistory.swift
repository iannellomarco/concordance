import AppKit

/// Text clipboard history (the last 200 entries), kept in Application Support. Entries that password managers
/// mark as concealed or transient are never recorded.
@MainActor
public final class ClipboardHistory {
    public struct Entry: Codable, Equatable {
        public var text: String
        public var date: Date
    }

    public private(set) var entries: [Entry] = []
    public var onChange: (() -> Void)?
    private var lastChangeCount = NSPasteboard.general.changeCount
    private var timer: Timer?
    private let fileURL = Paths.appSupport.appendingPathComponent("clipboard.json")
    private static let ignoredTypes: Set<String> = [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
    ]

    public init() {
        if let data = try? Data(contentsOf: fileURL), let saved = try? JSONDecoder().decode([Entry].self, from: data) {
            entries = saved
        }
    }

    public func start() {
        guard timer == nil else { return }
        timer = Timer.scheduledTimer(withTimeInterval: 0.5, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.poll() }
        }
    }

    public func stop() {
        timer?.invalidate()
        timer = nil
    }

    public func clear() {
        entries.removeAll()
        save()
        onChange?()
    }

    private func poll() {
        let pasteboard = NSPasteboard.general
        guard pasteboard.changeCount != lastChangeCount else { return }
        lastChangeCount = pasteboard.changeCount
        let types = Set((pasteboard.types ?? []).map(\.rawValue))
        guard types.isDisjoint(with: Self.ignoredTypes),
              let text = pasteboard.string(forType: .string),
              !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty, text.count < 200_000
        else { return }
        entries.removeAll { $0.text == text }
        entries.insert(Entry(text: text, date: Date()), at: 0)
        if entries.count > 200 { entries.removeLast(entries.count - 200) }
        save()
        onChange?()
    }

    private func save() {
        try? JSONEncoder().encode(entries).write(to: fileURL, options: .atomic)
    }

    /// FNV-1a, stable across launches (String.hashValue is seeded per process), so index entries survive restarts.
    static func stableHash(_ text: String) -> String {
        var hash: UInt64 = 0xcbf2_9ce4_8422_2325
        for byte in text.utf8 { hash = (hash ^ UInt64(byte)) &* 0x100_0000_01b3 }
        return String(hash, radix: 16)
    }

    func items() -> [SearchItem] {
        entries.map { entry in
            let firstLine = entry.text.split(whereSeparator: \.isNewline).first.map(String.init) ?? entry.text
            let title = firstLine.trimmingCharacters(in: .whitespaces)
            let relative = RelativeDateTimeFormatter().localizedString(for: entry.date, relativeTo: Date())
            return SearchItem(id: "clip:\(Self.stableHash(entry.text))", kind: .clipboard, title: String(title.prefix(120)),
                              subtitle: "Copied \(relative)", symbol: "doc.on.clipboard", date: entry.date,
                              signature: String(entry.text.prefix(1200)),
                              text: "title: none | text: \(entry.text.prefix(1200))", payload: entry.text)
        }
    }
}
